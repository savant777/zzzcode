-- All editor saves (including an explicit OVERWRITE) must call this RPC.
-- On conflict, ask the user again. An OVERWRITE sends the revision the user
-- just reviewed; never bypass the comparison, even for a confirmed overwrite.
CREATE OR REPLACE FUNCTION public.save_editor_backup(
    p_backup_id uuid,
    p_template_id bigint,
    p_access_token_hash text,
    p_expected_revision bigint,
    p_payload jsonb
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
    v_backup public.editor_backups%ROWTYPE;
BEGIN
    -- The server derives this hash from the raw bearer token, never accepts
    -- a client-supplied hash. Wrong token and absent ID get the same response.
    SELECT b.* INTO v_backup FROM public.editor_backups AS b
    WHERE b.id = p_backup_id AND b.template_id = p_template_id
      AND b.access_token_hash = p_access_token_hash
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN jsonb_build_object('status', 'not_found');
    END IF;
    IF p_expected_revision IS NULL OR p_expected_revision < 1 THEN
        RAISE EXCEPTION 'Expected revision must be a positive integer' USING ERRCODE = '22023';
    END IF;
    IF v_backup.revision <> p_expected_revision THEN
        RETURN jsonb_build_object('status', 'conflict', 'revision', v_backup.revision,
            'updatedAt', v_backup.updated_at);
    END IF;
    IF NOT public.editor_backup_payload_valid(p_payload) THEN
        RAISE EXCEPTION 'Invalid editor backup payload (maximum 2 MiB and 200 drafts)' USING ERRCODE = '22023';
    END IF;

    UPDATE public.editor_backups AS b
    SET payload = p_payload, revision = b.revision + 1, updated_at = clock_timestamp()
    WHERE b.id = v_backup.id
    RETURNING b.* INTO v_backup;

    RETURN jsonb_build_object('status', 'saved', 'id', v_backup.id,
        'revision', v_backup.revision, 'updatedAt', v_backup.updated_at);
END;
$$;

REVOKE ALL ON FUNCTION public.save_editor_backup(uuid, bigint, text, bigint, jsonb)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.save_editor_backup(uuid, bigint, text, bigint, jsonb)
    TO service_role;

COMMENT ON TABLE public.editor_backups IS
    'Private editor draft sets. Server-only access using a hashed link token; no user login required.';
NOTIFY pgrst, 'reload schema';
COMMIT;
