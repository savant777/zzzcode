CREATE OR REPLACE FUNCTION public.editor_backup_payload_valid(p_payload jsonb)
RETURNS boolean
LANGUAGE plpgsql IMMUTABLE SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
    v_draft jsonb;
    v_ids text[] := ARRAY[]::text[];
BEGIN
    IF p_payload IS NULL OR jsonb_typeof(p_payload) IS DISTINCT FROM 'object'
       OR octet_length(p_payload::text) > 2097152
       OR jsonb_typeof(p_payload->'activeDraftId') IS DISTINCT FROM 'string'
       OR jsonb_typeof(p_payload->'drafts') IS DISTINCT FROM 'array' THEN
        RETURN false;
    END IF;
    IF jsonb_array_length(p_payload->'drafts') NOT BETWEEN 1 AND 200 THEN
        RETURN false;
    END IF;
    FOR v_draft IN SELECT value FROM jsonb_array_elements(p_payload->'drafts') LOOP
        IF jsonb_typeof(v_draft) IS DISTINCT FROM 'object'
           OR jsonb_typeof(v_draft->'id') IS DISTINCT FROM 'string'
           OR length(v_draft->>'id') NOT BETWEEN 1 AND 200
           OR (v_draft->>'id') = ANY(v_ids)
           OR jsonb_typeof(v_draft->'name') IS DISTINCT FROM 'string'
           OR length(v_draft->>'name') NOT BETWEEN 1 AND 500
           OR jsonb_typeof(v_draft->'fieldValues') IS DISTINCT FROM 'object'
           OR jsonb_typeof(v_draft->'updatedAt') IS DISTINCT FROM 'string' THEN
            RETURN false;
        END IF;
        v_ids := array_append(v_ids, v_draft->>'id');
    END LOOP;
    RETURN (p_payload->>'activeDraftId') = ANY(v_ids);
END;
$$;

REVOKE ALL ON FUNCTION public.editor_backup_payload_valid(jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.editor_backup_payload_valid(jsonb) TO service_role;

CREATE TABLE IF NOT EXISTS public.editor_backups (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    template_id bigint NOT NULL REFERENCES public.templates(id) ON DELETE CASCADE,
    -- SHA-256 hex of a random 32-byte token generated by the server.
    -- Never store the raw link token or return this hash to the browser.
    access_token_hash text NOT NULL CHECK (access_token_hash ~ '^[0-9a-f]{64}$'),
    payload jsonb NOT NULL CHECK (public.editor_backup_payload_valid(payload)),
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS editor_backups_template_id_idx ON public.editor_backups(template_id);

ALTER TABLE public.editor_backups ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.editor_backups FORCE ROW LEVEL SECURITY;
